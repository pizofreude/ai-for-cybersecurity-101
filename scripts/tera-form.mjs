// Writes chapters/README.md: the Tera chapter form fields for every chapter, read from front matter.
//   node scripts/tera-form.mjs           rewrite chapters/README.md
//   node scripts/tera-form.mjs --check   fail if chapters/README.md is out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = path.join(root, 'chapters');
const target = path.join(dir, 'README.md');

function frontMatter(text) {
  const match = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n/);
  return Object.fromEntries(match[1].split('\n').map((line) => {
    const i = line.indexOf(':');
    return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
  }));
}

const chapters = readdirSync(dir)
  .filter((f) => /^ch\d-.*\.md$/.test(f))
  .sort()
  .map((file) => ({ file, ...frontMatter(readFileSync(path.join(dir, file), 'utf8')) }));

// The Tera chapter editor's REVIEW values.
const REVIEW = { 'self-check': 'auto complete', approval: 'lecturer approval' };

const lines = [
  '# Tera chapter form sheet',
  '',
  'Generated by `node scripts/tera-form.mjs` from each chapter\'s front matter. Edit the chapter files, not this sheet.',
  '',
  'Course: AI for Cybersecurity 101. Free track. Physical class, own laptop. 20 minutes of pre-work plus 180 minutes in session.',
  '',
  '| Chapter | Block | Duration | Review | File |',
  '|---|---|---|---|---|',
  ...chapters.map((c) => `| ${c.chapter}. ${c.title} | ${c.block} | ${c.duration_min} min | ${REVIEW[c.review]} | [${c.file}](${c.file}) |`),
  '| - | Break (between CH4 and CH5) | 10 min | - | - |',
  '',
];

for (const c of chapters) {
  lines.push(
    `## Chapter ${c.chapter}: ${c.title}`,
    '',
    '| Tera field | Value |',
    '|---|---|',
    `| Title | ${c.title} |`,
    `| Summary | ${c.summary} |`,
    `| Block | ${c.block} |`,
    `| Duration | ${c.duration_min} min |`,
    `| Deliverable | ${c.tera_deliverable} (hand-in: ${c.deliverable}) |`,
    `| Review | ${REVIEW[c.review]} |`,
    `| Lesson | Paste all of [tera/${c.file}](../tera/${c.file}), generated by \`node scripts/tera-lesson.mjs\` |`,
    '',
  );
}

lines.push(
  '## Before pasting into Tera',
  '',
  '- The course repository is public at https://github.com/pizofreude/ai-for-cybersecurity-101, so students clone it in CH1 without an account.',
  '- The lesson files in `tera/` follow the editor\'s Step syntax: one `## Steps` section with a `###` heading per step, a `Cap:` line per timed step, and a `## Checkpoint` hand-in.',
  '- Chapter 1 opens on enrolment, so it carries the pre-work. Chapters 2 to 6 open on class day.',
  '- Chapter 6 uses approval review. Set a primary trainer on the session so the completion certificate issues.',
  '',
);

const output = lines.join('\n');
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  if (current !== output) {
    console.log('FAIL  chapters/README.md is out of date. Run: node scripts/tera-form.mjs');
    process.exit(1);
  }
  console.log('PASS  chapters/README.md matches the chapter front matter');
} else {
  writeFileSync(target, output);
  console.log(`Wrote chapters/README.md for ${chapters.length} chapters`);
}
