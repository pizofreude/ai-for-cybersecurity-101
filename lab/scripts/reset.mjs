// One command to rebuild the lab: keys in .env.local, schema, and seed data.
//   npm run reset                    restore seed data, keep keys
//   npm run reset -- --rotate-keys   also generate new keys
//   npm run reset -- --code          restore the lab code to the vulnerable baseline, so every flag is open again,
//                                    then rotate keys and restore data. Uncommitted changes go to git stash first.
import { execFileSync } from 'node:child_process';
import { randomBytes, scryptSync } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { labRoot, openDb } from '../emulator/db.mjs';
import { sign } from '../emulator/jwt.mjs';
import * as seed from '../db/seed.mjs';

const args = new Set(process.argv.slice(2));
const envPath = path.join(labRoot, '.env.local');

function readEnv() {
  if (!existsSync(envPath)) return {};
  return Object.fromEntries(
    readFileSync(envPath, 'utf8')
      .split(/\r?\n/)
      .filter((line) => /^[A-Z_]+=/.test(line))
      .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]),
  );
}

function writeKeys(previous) {
  const jwtSecret = randomBytes(32).toString('hex');
  const tenYears = Math.floor(Date.now() / 1000) + 10 * 365 * 24 * 3600;
  const key = (role) => sign({ iss: 'ai4cyber-lab', role, iat: Math.floor(Date.now() / 1000), exp: tenYears }, jwtSecret);
  const serviceKey = key('service_role');
  const lines = [
    '# Generated by npm run reset. Fake lab values: never reuse them anywhere else.',
    'NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:54321',
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${key('anon')}`,
    `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
    `SUPABASE_JWT_SECRET=${jwtSecret}`,
    `LAB_WEBHOOK_SECRET=whsec_lab_${randomBytes(24).toString('hex')}`,
    '# Optional: set a real key to run the chatbot on Claude instead of the simulated model.',
    `ANTHROPIC_API_KEY=${previous.ANTHROPIC_API_KEY ?? ''}`,
    '',
  ];
  writeFileSync(envPath, lines.join('\n'));
}

function hashPassword(password) {
  const salt = randomBytes(16).toString('hex');
  return `scrypt$${salt}$${scryptSync(password, salt, 32).toString('hex')}`;
}

function insertAll(db, table, rows) {
  for (const row of rows) {
    const cols = Object.keys(row);
    db.prepare(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(() => '?').join(', ')})`).run(...Object.values(row));
  }
}

// Restores lab/ to the vulnerable baseline (origin/main, or main without a remote), even when fixes were committed.
// Uncommitted work goes to git stash first. Commits are never touched.
function restoreCode() {
  const git = (...gitArgs) => execFileSync('git', gitArgs, { cwd: labRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  const hasRef = (ref) => {
    try {
      git('rev-parse', '--verify', '--quiet', ref);
      return true;
    } catch {
      return false;
    }
  };
  const baseline = hasRef('origin/main') ? 'origin/main' : 'main';
  if (git('status', '--porcelain', '--', '.')) {
    git('stash', 'push', '--include-untracked', '-m', `lab work saved by npm run reset ${new Date().toISOString()}`, '--', '.');
    console.log('Your uncommitted lab changes are in git stash: "git stash pop" brings them back.');
  }
  git('restore', `--source=${baseline}`, '--staged', '--worktree', '--', '.');
  console.log(`Lab code restored from ${baseline}: every flag is open again. Your commits are untouched.`);
  // Run the restored reset script, so keys and data match the restored code (F1 needs its public key back).
  execFileSync(process.execPath, [path.join(labRoot, 'scripts', 'reset.mjs'), '--rotate-keys'], { cwd: labRoot, stdio: 'inherit' });
  console.log('Restart npm run dev so the app and the emulator load the restored code and keys.');
  process.exit(0);
}

if (args.has('--code')) restoreCode();

const previous = readEnv();
if (args.has('--rotate-keys') || !previous.SUPABASE_JWT_SECRET) {
  writeKeys(previous);
  console.log('Keys written to lab/.env.local. Restart npm run dev if it is running.');
}

const db = openDb();
const now = () => new Date().toISOString();
db.exec('PRAGMA foreign_keys = OFF;');
for (const { name } of db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'").all()) {
  db.exec(`DROP TABLE IF EXISTS "${name}"`);
}
db.exec(readFileSync(path.join(labRoot, 'db', 'schema.sql'), 'utf8'));
db.exec('PRAGMA foreign_keys = ON;');

insertAll(db, 'users', seed.accounts.map((a) => ({ id: a.id, email: a.email, password_hash: hashPassword(a.password), created_at: now() })));
insertAll(db, 'profiles', seed.accounts.map((a) => ({ id: a.id, display_name: a.display_name, phone: a.phone, is_admin: a.is_admin })));
insertAll(db, 'notes', seed.notes.map((n) => ({ ...n, created_at: now() })));
insertAll(db, 'products', seed.products);
insertAll(db, 'comments', seed.comments.map((c) => ({ ...c, created_at: now() })));
insertAll(db, 'orders', seed.orders.map((o) => ({ ...o, created_at: now() })));
insertAll(db, 'coupons', seed.coupons);
db.close();

console.log('Lab data restored to seed state.');
